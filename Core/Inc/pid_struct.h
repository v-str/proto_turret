#ifndef PID_STRUCT_H
#define PID_STRUCT_H

typedef struct {
  // Коэффициенты (настраиваемые)

  // Kp
  // Реагирует на текущую ошибку. Чем больше ошибка — тем сильнее крутит мотор.
  // Увеличивать, пока мотор не начнёт реагировать. Слишком большое значение →
  // будут колебания.
  float kp;  // Пропорциональный — сила реакции на текущую ошибку

  // Ki
  // Убирает остаточную ошибку (если мотор не доворачивает до цели).
  // Добавлять по чуть-чуть, если мотор постоянно не доворачивает. Слишком
  // большое значение → будет перелёт.
  float ki;  // Интегральный — убирает остаточную ошибку (нужен для точного
             // попадания)

  // Kd
  // Гасит колебания. Как демпфер — чем больше, тем плавнее остановка.
  // Увеличивать, если мотор колеблется около цели. При переборе → вялая
  // реакция.
  float kd;  // Дифференциальный — гасит колебания (демпфер)

  // Состояния (внутренние, меняются при вызове)
  float integral;    // Накопленная ошибка (сумма ошибок * dt)
  float prev_error;  // Ошибка на предыдущем шаге (для расчёта производной)

  // Ограничения (защита)
  float output_min;  // Минимальное значение выхода (например, -100)
  float output_max;  // Максимальное значение выхода (например, 100)
  float dt;          // Период вызова регулятора (в секундах)
} PID_Struct;

// Инициализация регулятора
// Вызывается один раз при старте, задаёт коэффициенты и период.
void pid_init(PID_Struct* pid, float kp, float ki, float kd, float dt);

// Обновление регулятора
// Вызывается циклически (каждые dt секунд).
// setpoint — целевое значение (чего хотим достичь)
// measurement — текущее значение (что имеем)
// Возвращает управляющий сигнал (скорость или усилие)
float pid_update(PID_Struct* pid, float setpoint, float measurement);

#endif  // PID_STRUCT_H